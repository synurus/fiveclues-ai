-- ─────────────────────────────────────────────────────────────
-- 6. 함수
-- ─────────────────────────────────────────────────────────────
-- [원본] ✅ 2026-09-02 에 실제 정의를 받아 그대로 넣었다(pg_get_functiondef 결과).
--        저장소엔 정의가 없고 DB 안에만 있던 함수다
--        (apps/backend/src/db/game.ts 주석: "그 정의가 저장소에 없다(DB 안에만 있음)").
--
-- 원본을 받아보고 확인된 것:
--   · games 행을 먼저 넣고 그 id 로 players 를 넣는다 → 위 games 쪽 라벨 복합 FK 는
--     반드시 DEFERRABLE INITIALLY DEFERRED 여야 한다. 즉시 검사면 첫 INSERT 에서
--     "참가자가 아직 없다"로 실패한다.
--   · 방 번호 중복은 이 함수가 신경 쓰지 않는다 — 방 생성 단계에서 서버가 이미 거른다
--     (games.room_id 주석 참고).
--   · RETURNS bigint 인데 games.id 는 integer 다. 1차 설계에서 PK 가 bigint 였던 흔적으로
--     보인다(나중에 integer 로 바꾸면서 함수 시그니처는 안 건드림). integer → bigint 는
--     암묵적으로 넓어지므로 동작에 문제가 없어 원본 그대로 둔다.
--
-- 참고: Supabase 린터는 search_path 가 고정되지 않은 함수에 경고를 낸다. 이 함수는
--       SECURITY INVOKER(기본값)라 위험이 낮아 원본을 그대로 뒀다. 경고를 없애려면
--       LANGUAGE plpgsql 줄 다음에 `SET search_path = public` 한 줄을 넣으면 된다.

CREATE OR REPLACE FUNCTION public.fn_start_game(p_room_id text, p_category text, p_word text, p_bot_label text, p_liar_label text, p_players jsonb)
 RETURNS bigint
 LANGUAGE plpgsql
AS $function$
declare
  v_game_id bigint;
begin
  insert into games (room_id, category, word, bot_label, liar_label)
  values (p_room_id, p_category, p_word, p_bot_label, p_liar_label)
  returning id into v_game_id;

  insert into players (game_id, player_label, is_bot, role)
  select v_game_id, (p)->>'label', ((p)->>'is_bot')::bool, (p)->>'role'
  from jsonb_array_elements(p_players) as p;

  return v_game_id;
end;
$function$;

