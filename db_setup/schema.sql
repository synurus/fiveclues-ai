--
-- ⚠️ 원본 DB에서 아직 확인 못 한 것:
--   - 원본의 ON DELETE 동작 — 여기 값은 이 스키마를 쓰는 쪽의 선택이다
--   - 뷰 2개(v_survey_reason_counts, v_survey_free_texts) — 앱 코드가 안 쓰는 걸
--     확인해서(레포 전수) 옮기지 않았다. 필요하면 새로 쓰면 된다.

