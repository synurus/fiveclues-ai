-- ─────────────────────────────────────────────────────────────
-- 2. 테이블
-- ─────────────────────────────────────────────────────────────
-- [원본] 컬럼·타입·NOT NULL·DEFAULT
-- [추정] integer PK 5개의 GENERATED ... AS IDENTITY
--        내보낸 정의엔 자동 증가가 빠져 있었다. 앱 코드 어디서도 이 id 들을 직접 넣지
--        않으므로(games 는 fn_start_game 이 RETURNING 으로 받고, 나머지는 마스터 데이터)
--        DB 가 만들어주지 않으면 INSERT 가 바로 실패한다.
--        BY DEFAULT 로 둔 이유: 나중에 원본 데이터를 id 까지 그대로 복원할 때
--        명시적 id 를 넣을 수 있어야 한다(ALWAYS 면 OVERRIDING 절이 필요해진다).

CREATE TABLE categories (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE words (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  category_id integer NOT NULL,
  text text NOT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE games (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  -- 방 번호. 유니크가 아니다 — 같은 방에서 여러 판을 하면 판마다 행이 쌓인다.
  -- 방 이름·번호 중복은 서버가 방 생성 단계에서 막는다(index.ts 의 'join' 처리):
  -- 이미 있는 방이면 그 방에 입장시키고, 없는 번호로 title 없이 들어오면 "없는 방입니다"로
  -- 거절한다. 즉 DB 가 관여할 문제가 아니다.
  room_id text NOT NULL,
  category text NOT NULL,
  word text NOT NULL,
  -- category/word 는 FK 가 아니라 글자 그대로 저장한다.
  -- "기록은 사진이지 링크가 아니다" — 나중에 단어 목록을 갈아도 지난 판의 기록은 안 변한다.
  bot_label text NOT NULL,
  liar_label text NOT NULL,
  liar_game_result text,
  bot_detected_count integer NOT NULL DEFAULT 0,
  bot_voter_total integer NOT NULL DEFAULT 0,
  final_round integer NOT NULL DEFAULT 1,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  ended_at timestamp with time zone,
  -- 판마다 "실제로 어떤 봇이 돌았는지". SHA 만으로는 부족하다 —
  -- /x/provider 가 재배포 없이 프로바이더를 바꿔서 같은 SHA 에 다른 봇인 판이 생긴다.
  bot_commit_sha text,
  bot_provider text,
  bot_model text,
  PRIMARY KEY (id)
);

CREATE TABLE players (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  game_id integer NOT NULL,
  player_label text NOT NULL,
  is_bot boolean NOT NULL DEFAULT false,
  role text NOT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE game_messages (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  game_id integer NOT NULL,
  speaker_label text,          -- 시스템 메시지는 화자가 없다
  speaker_type speaker_type NOT NULL,
  role text,                   -- 시스템 메시지는 역할도 없다
  round integer NOT NULL DEFAULT 1,
  phase text NOT NULL,
  text text NOT NULL,
  at timestamp with time zone NOT NULL DEFAULT now(),
  -- 화면이 들고 있는 Message.id(m{ts}_{rand} / sys{ts}_{n}).
  -- PK(uuid)는 DB 가 만든 값이라 "화면에서 고른 그 발언"을 되짚을 수 없어서 칸을 더했다.
  runtime_id text,
  PRIMARY KEY (id)
);

CREATE TABLE game_votes (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  game_id integer NOT NULL,
  round integer NOT NULL DEFAULT 1,
  vote_type text NOT NULL,
  phase text NOT NULL,
  voter_label text NOT NULL,
  -- 기권은 아예 기록하지 않는다(index.ts 가 targetId 가 있을 때만 logVote 를 부른다).
  -- 그래서 이 칸은 항상 실재하는 참가자 라벨이고, 아래 복합 FK 를 걸 수 있다.
  target_label text NOT NULL,
  at timestamp with time zone NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE survey_questions (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  code text NOT NULL,
  text text NOT NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  description text,
  -- 문항은 덮어쓰지 않고 세대별로 쌓는다. 코드는 활성 세대 하나만 읽는다.
  is_active boolean NOT NULL DEFAULT false,
  PRIMARY KEY (id)
);

CREATE TABLE survey_reasons (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  question_id integer NOT NULL,
  code text NOT NULL,
  text text NOT NULL,
  sort_order integer NOT NULL DEFAULT 0,
  is_other boolean NOT NULL DEFAULT false,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  PRIMARY KEY (id)
);

CREATE TABLE survey_responses (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  game_id integer NOT NULL,
  voter_label text NOT NULL,
  -- 봇 지목(20초 타이머)을 놓치면 이 두 칸이 null 이다. 지목과 설문은 별개 정보라
  -- 하나가 없다고 설문 본문까지 버리지 않는다.
  -- "지목 안 함" = guessed_bot_label IS NULL / "지목했는데 틀림" = guessed_correctly = false
  guessed_bot_label text,
  guessed_correctly boolean,
  free_text text,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  -- "가장 봇 같았던 발언"으로 고른 game_messages.runtime_id. 안 골랐으면 null.
  picked_message_runtime_id text,
  PRIMARY KEY (id)
);

CREATE TABLE survey_response_reasons (
  survey_response_id uuid NOT NULL,
  reason_id integer NOT NULL,
  free_text text,
  PRIMARY KEY (survey_response_id, reason_id)
);

