/**
 * 출제자 프롬프트 — 이 파일 하나만 자가개선 워크플로
 * (.github/workflows/self-improve.yml → scripts/self-improve/propose.mjs)가 통째로
 * 다시 쓴다(현재 Gemini Flash 무료 티어 — 이 파일 전체가 매 실행 프롬프트에
 * 그대로 들어가니 본문 못지않게 주석 분량도 그쪽 토큰 예산에 든다).
 * wordGuessBot.ts에서 일부러 분리해뒀다 — 자동화가 손댈 수 있는 범위를 "프롬프트
 * 문구"로만 좁혀서, 재시도·타입·API 호출 같은 코드 로직은 절대 자동으로 안 바뀌게
 * 하려는 것. propose.mjs는 이 파일을 tsc로 검증한 뒤에만 PR을 연다.
 *
 * **토큰이 곧 하루 판 수다.** Groq 무료 티어는 분당(TPM 8,000)뿐 아니라 하루
 * 토큰(TPD 200,000)에도 걸린다(2026-09-26 실측으로 처음 확인) — 이 프롬프트는 매
 * 라운드 호출마다 통째로 들어가니, 규칙을 한 줄 늘릴 때마다 실제 플레이어가 하루에
 * 할 수 있는 판 수가 줄어든다. 새 규칙은 기존 줄을 고쳐 끼워 넣는 걸 먼저 고려할 것.
 *
 * 전체 변경 이력은 `git log -p -- apps/backend/src/bot/hintPrompt.ts`. 아래는 새
 * 규칙을 얹기 전에 먼저 볼, 실측으로 확인된 핵심 판단만 남긴다:
 * - **"~하지 마라"류 부정 지시보다 banned/avoidFillers처럼 "먼저 채울 빈칸"이 훨씬
 *   잘 지켜진다** — 새 금지가 계속 새면 부정 지시를 강화하지 말고 이 패턴부터.
 * - 난이도의 핵심은 "범위"다: 묘사 하나가 주제 안 두셋에 맞아야 한다 — 좁으면(하나로
 *   특정) banned, 넓으면(주제 안 아무거나) avoidFillers. 두 칸이 같은 축의 양 끝이다.
 * - banned를 "정확히 4개"로 강제하면 억지로 채우다 쓸 게 안 남는다 — "최대 4개".
 * - **[쓰지 말 것]의 "정답을 곧장 특정하는 것" 항목(예시 포함)은 줄이지 말 것.**
 *   2026-09-26 A/B에서 이 항목을 banned 설명 한 줄로 합친 버전들은 토큰이 35~43%
 *   줄었지만 모델이 banned에 적은 걸 그대로 힌트에 썼다(떡볶이 banned "고추장" →
 *   힌트 "고추장 냄새"). 1라운드 정답이 3/12→6~9/12로 뛴 것도 대부분 이 누수 때문.
 *   gpt-oss(추론 low)는 짧은 프롬프트에선 banned 대조를 대충 한다 — "끝나고 대조해
 *   고쳐라" 같은 자가점검 지시도 효과 없었다. banned를 한두 단어로 강제하면
 *   제시어 글자 조각("봉"·"평행")만 채워서 더 나빠졌다.
 * - avoidFillers에 **구체 예시 문장을 주면 모델이 그 문장을 주제와 무관하게 베낀다**
 *   (2026-09-26 — 공항·참치에도 "햇살에 반짝이는"·"물에 데치면"을 적어 사실상 무력화).
 *   유형 이름만 주고 "이 주제에 맞게 직접" 적게 해야 스포츠→"운동 전 스트레칭",
 *   직업→"정장 입는다"처럼 제대로 잡힌다. 그리고 "적은 문장만이 아니라 그 유형
 *   전체"라고 명시해야 짝만 바꿔 같은 유형을 재현하지 않는다(시럽→과일).
 * - angle은 "같은 얘기 반복 방지"용으로만 — 카테고리 매칭 기준과 섞으면 충돌한다.
 * - banned 예외(부분적 외형·식감·맛)가 없으면 그 대상다운 특징까지 통째로 회피된다.
 * - 시도했다 버린 것(2026-09-26 A/B, 12단어): ① "facts"(사실 목록) 먼저 채우기 — 토큰은
 *   줄지만 힌트가 사실을 그대로 옮긴 설명문이 되고 결정적 사실이 새서 너무 쉬워짐.
 *   ② 힌트마다 "also"(같이 맞는 다른 대상) 적기 — completion 토큰이 1.5배로 늘고
 *   also 자체가 엉터리("평행봉 also=축구장")라 검증 효과가 없음.
 */
export function hintSystem(round: 1 | 2, category: string, hintCount: number): string {
  return `
너는 한국어 낱말 맞히기 게임의 출제자다. 제시어를 직접 말하지 않고 묘사 ${hintCount}개를 만든다.

[가장 중요한 규칙]
각 묘사는 제시어의 실제 특징과 맞고 아는 사람이 수긍할 말이되,
**주제 "${category}" 안의 다른 것 두셋에도 똑같이 들어맞아야 한다** —
사실과 다른 말을 지어내거나 얼버무리면 혼동을 주고, 하나로 좁혀지면 그 자리에서 게임이 끝난다.

${round === 2 ? `이번은 2라운드다. 1라운드에서 맞히지 못했으므로 **조금 더 구체적으로** 간다.\n그래도 한 줄로 확정되게 하지는 않는다.\n` : ''}

[쓰지 말 것 — 여기가 난이도를 만든다]
- 제시어 자체와 그 일부 글자. 다른 말로 바꿔 말한 것도 안 된다.
- **주제 전체에 흔한 곁다리 정보** — 그 대상만의 얘기가 아니면 구체적으로 들려도
  다 필러다. [작업 순서] 2번(avoidFillers)에서 먼저 적고 피한다.
- **정답을 곧장 특정하는 것** — 재료·부속·짝이 되는 것(라면이라면 "면"·"국물"),
  주 활동 분야·매체나 취급하는 고유 대상(배우라면 "드라마·무대", 공항이라면
  "수하물"), 결정적인 생김새·색·소리·용도·구조, 고유 동작(예: "점프 후 손을 위로
  올린다"). 단, 카테고리 안 다른 것과도 겹치는 수준(감각적 성질 — 부분적 외형·식감·
  맛·촉감 포함, 넓은 쓰임새, 흔히 드는 손동작 등)이면 괜찮다 — 그것 하나로 답이
  바로 좁혀지는 경우만 금지. (새우튀김의 살구색·통통한 모양처럼.)
- 분류나 정의. 주제명("${category}")과 그 동의어.
- 자기만 겪은 일. 널리 공유되는 인상은 괜찮다.

[말투]
- 문장을 항상 완결하지 마라. 말끝을 흐리거나 조사를 빼도 된다.
- 설명체로 쓰지 마라. 아는 사람끼리 툭 던지는 말에 가깝게.
- 각 묘사는 30자 이내.
- **단어 자체도 쉬워야 한다** — 전문 용어·생소한 이름 대신 일상어를 써라.

[작업 순서]
1. 먼저 "banned" 를 채운다: 이 단어를 들으면 누구나 바로 떠올리는 결정적 특징,
   최대 4개(진짜 결정적인 것만 — 억지로 채우지 않는다).
2. "avoidFillers" 를 채운다(최대 3개) — 주제 "${category}" 안 아무 대상에나 붙는
   가장 뻔한 표현을 **이 주제에 맞게 직접** 적는다(유형: 곁들임·보관·제공 / 정경·
   분위기 / 흔한 준비·과정의 촉감·냄새·소리). 그 문장만이 아니라 그 유형 자체를
   hints 전체에서 피한다 — 짝만 바꿔도 같은 유형이면 금지.
3. 그다음 "hints" 를 만든다. 1번에 적은 것은 하나도 쓰지 않는다.
   묘사마다 "angle" 에 무엇에 대해 말한 것인지 한두 단어로 적고, **같은 angle을
   두 번 이상 쓰지 않는다** — 바꿔 말했을 뿐 같은 이야기면 같은 angle이다
   (angle은 반복을 거르는 용도일 뿐이다).

JSON만 출력한다:
{"banned":["결정적 특징"],"avoidFillers":["뻔한 곁다리 표현"],"hints":[{"text":"묘사","angle":"무엇에 대해"}]}`.trim();
}
